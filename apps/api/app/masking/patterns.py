"""Compiled regexes and word lists for the masking engine (no logic here).

All patterns were exercised against synthetic samples shaped like the real Confluence 설문/수요조사 pages
(phone: 0xx-xxxx-xxxx, full road address, 5-digit 사번 next to a 사번 label/column).
"""

from __future__ import annotations

import re

_REGION = (
    r"(?:서울특별시|서울시|서울|부산광역시|부산|대구광역시|대구|인천광역시|인천|광주광역시|광주|대전광역시|대전|"
    r"울산광역시|울산|세종특별자치시|세종|경기도|경기|강원특별자치도|강원도|강원|충청북도|충북|충청남도|충남|"
    r"전북특별자치도|전라북도|전북|전라남도|전남|경상북도|경북|경상남도|경남|제주특별자치도|제주도|제주)"
)

# 시·도 + (시|군|구) 1~2개 + (도로명[+번지] | 읍면동리 + 지번) + 건물/동/호/층 꼬리표 반복
ADDR = re.compile(
    r"(?:\(\d{5}\)\s*)?"
    + _REGION
    + r"\s+(?:[가-힣]+(?:시|군|구)\s+){1,2}"
    + r"(?:[가-힣0-9]+(?:로|길)(?:\d+번길)?(?:\s+\d+(?:-\d+)?)?|[가-힣0-9]+(?:동|읍|면|리)\s+\d+(?:-\d+)?(?:번지)?)"
    + r"(?:\s+[가-힣A-Za-z0-9\-]+(?:아파트|빌라|타워|빌딩|오피스텔|APT|동|호|층))*"
)

_D = "[0-9０-９]"                                   # ASCII + 전각 숫자
_Z = "[\u200b-\u200d\ufeff]*"                           # 제로폭 문자
_S = _Z + "[ \t\xa0.\\-\u2010-\u2015\u2212]" + _Z         # 구분자 1개(공백·점·하이픈류) + 제로폭 허용
PHONE = re.compile(
    r"(?:(?<!" + _D + r")(?:"
    + r"(?:\([0０]" + _D + r"{1,2}\)(?:" + _S + r")?|[0０]" + _D + r"{1,2}" + _S + r")" + _D + r"{3,4}" + _S + _D + r"{4}"
    + r"|[0０][1１]" + _D + r"{8,9})"
    + r"|(?<![0-9A-Za-z_+])\+82(?:(?:" + _S + r")?\(?[0０]?" + _D + r"{1,2}\)?" + _S + _D + r"{3,4}" + _S + _D + r"{4}"
    + r"|" + _D + r"{9,10}))(?!" + _D + r")"
)

_V4 = r"(?:25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)"
# 앞뒤 글자(한글·영문·밑줄)가 붙어 있어도 잡는다(예: "10.1.2.3에서", "node_10.0.0.5_80"). 숫자·점이 붙거나 v/V 접두(버전)면 제외.
IPV4 = re.compile(r"(?<![0-9.])(?<![vV])(?:" + _V4 + r"\.){3}" + _V4 + r"(?!\d)(?!\.\d)")

_H = r"[0-9A-Fa-f]{1,4}"
IPV6 = re.compile(
    r"(?<![0-9A-Za-z_:])(?:(?:" + _H + r":){7}" + _H
    + r"|(?:" + _H + r":){1,7}:(?:" + _H + r"(?::" + _H + r"){0,6})?"
    + r"|::(?:" + _H + r"(?::" + _H + r"){0,6}))(?![0-9A-Za-z_:])"
)

# 사번은 문맥(라벨/열)에서만 잡는다. 5자리 숫자 단독은 대상 아님.
LABEL_SABUN = re.compile(r"((?:사번|사원\s*번호)\s*[:：=(（]?\s*)(\d{5})(?!\d)")
_NAME_LABELS = ("이름", "성명", "신청인", "수령인", "받는분")
# 라벨 글자 사이에 공백이 있어도 잡는다(예: "신 청 인 :").
LABEL_NAME = re.compile(
    r"((?<![가-힣])(?:" + "|".join(r"\s*".join(lb) for lb in _NAME_LABELS) + r")\s*[:：=]\s*)([가-힣]{2,4}|[가-힣](?: [가-힣]){1,3}(?![가-힣]))"
)

# 개인정보가 걸린 줄에서만 쓰는 이름 후보(좁은 규칙 3가지; 일반 문장을 건드리지 않도록).
_SURNAMES = (
    "김이박최정강조윤장임한오서신권황안송류전홍고문양손배백허유남심노하곽성차주우구민나진지엄채원천방"
    "공현함변염여추도소석선설마길연위표명기반왕금옥육인맹제모탁국어은편용예경봉사부"
)
_TITLES = "그룹장|파트장|센터장|연구위원|상무|전무|이사|사장|실장|박사|교수|프로|님|책임|수석|선임|사원|매니저|과장|차장|부장|대리|팀장|연구원"
# 1) 성씨로 시작하는 정확히 3자(조사·어미 는를의로에과와 + 면다요며고 로 끝나면 제외)
NAME_3 = re.compile(r"(?<![가-힣])([" + _SURNAMES + r"][가-힣](?![는를의로에과와면다요며고])[가-힣])(?![가-힣])")
# 2) 성씨로 시작하는 2자: 바로 뒤(공백 0~1개)에 직급이 올 때만. 직급은 마스킹하지 않는다.
NAME_2_TITLE = re.compile(r"(?<![가-힣])([" + _SURNAMES + r"][가-힣])(?= ?(?:" + _TITLES + r")(?![가-힣]))")
# 3) 복성으로 시작하는 정확히 4자
NAME_4_COMPOUND = re.compile(r"(?<![가-힣])((?:남궁|선우|제갈|독고|황보|사공)[가-힣]{2})(?![가-힣])")
NAME_RULES = (NAME_4_COMPOUND, NAME_3, NAME_2_TITLE)
# 이름 열(헤더에 정확히 이 단어가 있는 표)
NAME_HEADERS = ("이름", "성명")
NAME_STOPWORDS = frozenset(
    "사번 이름 성명 주소 전화 연락처 핸드폰 휴대폰 배송지 신청인 수량 금액 비고 구분 조편성 시작일 종료일 "
    "프로 책임 수석 선임 사원 매니저 과장 차장 부장 대리 팀장 연구원 그룹장 파트장 센터장 연구위원 상무 전무 이사 사장 실장 박사 교수 담당 인프라 서비스 시스템 사업부 사업장 기술팀 운영팀 고객사 관리자 운영자 전산실 소프트 도메인 마스터 나머지 정보팀 서버실 인터넷 장애건 유지보수 부서 참석 참여 신청 확인 변경 업데이트".split()
)

BUILTIN_ALLOW = frozenset({"127.0.0.1", "0.0.0.0", "::1"})


EMAIL = re.compile(
    r"(?<![A-Za-z0-9._%+\-])[A-Za-z0-9][A-Za-z0-9._%+\-]*@(?:[A-Za-z0-9](?:[A-Za-z0-9\-]*[A-Za-z0-9])?\.)+[A-Za-z]{2,}(?![A-Za-z0-9])"
)
